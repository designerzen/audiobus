const COMPOSITE_DRUM_LANES = Object.freeze([
	'kick',
	'snare',
	'hat',
	'clap',
	...AUXILIARY_DRUM_LANES,
])
const greatestCommonDivisor = (a: number, b: number): number =>
	b ? greatestCommonDivisor(b, a % b) : a
const leastCommonMultiple = (a: number, b: number): number => (a * b) / greatestCommonDivisor(a, b)

/** Overlay grooves without summing their velocities, which avoids clipping. */
export const createCompositeDrumGroove = (grooves: readonly DrumGroove[]): DrumGroove | null => {
	const selected = grooves.filter((item) => item?.kick?.length)
	if (!selected.length) return null
	if (selected.length === 1) return selected[0]

	const length = selected.reduce(
		(combined, item) => leastCommonMultiple(combined, item.kick.length),
		1,
	)
	const composite = {} as DrumGroove
	for (const lane of COMPOSITE_DRUM_LANES) {
		composite[lane] = Array.from({ length }, (_, step) =>
			selected.reduce((velocity, item) => {
				const sequence = item[lane]
				return Array.isArray(sequence) && sequence.length
					? Math.max(velocity, sequence[step % sequence.length])
					: velocity
			}, 0),
		)
	}
	return composite
}

