export interface ScoreNote {
	/** Onset time in seconds. */
	time: number
	/** MIDI note number (0–127). */
	midi: number
	/** Duration in seconds. */
	duration: number
	/** Normalized velocity (0–1). */
	velocity: number
}

export interface PianoRollScore {
	id: PianoRollScoreId
	title: string
	composer: string
	notes: readonly ScoreNote[]
	duration: number
}

type Tuple = readonly [time: number, midi: number, duration: number, velocity: number]

function buildScore(
	id: PianoRollScoreId,
	title: string,
	composer: string,
	tuples: readonly Tuple[]
): PianoRollScore {
	const notes = tuples.map(([time, midi, duration, velocity]) => ({
		time,
		midi,
		duration,
		velocity
	}))
	const duration = notes.reduce((end, note) => Math.max(end, note.time + note.duration), 0)
	return { id, title, composer, notes, duration }
}

